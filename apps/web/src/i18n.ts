const DICTS = { nl, en } as const;
export type Lang = keyof typeof DICTS;
export type LangPref = 'auto' | Lang;
/** Naam van elke taal in die taal zelf. */
export const LANG_NAMES: Record<Lang, string> = { nl: 'Nederlands', en: 'English' };
export const LANGS = Object.keys(DICTS) as Lang[];
const FALLBACK: Lang = 'en';
const KEY = 'pp.lang';

const isLang = (v: unknown): v is Lang => typeof v === 'string' && v in DICTS;

export function getLangPref(): LangPref {
  try { const v = localStorage.getItem(KEY); return isLang(v) ? v : 'auto'; } catch { return 'auto'; }
}

/** Eerste taal uit de telefooninstellingen die de app heeft; anders Engels. */
export function detectLang(): Lang {
  const list = (navigator.languages?.length ? navigator.languages : [navigator.language]).filter(Boolean);
  for (const tag of list) {
    const base = tag.toLowerCase().split(/[-_]/)[0];
    if (isLang(base)) return base;
  }
  return FALLBACK;
}

export let lang: Lang = FALLBACK;
/** Het actieve woordenboek. Live binding: na `applyLang()` zien alle modules de nieuwe taal. */
export let t: Dict = DICTS[FALLBACK];

export function applyLang(): Lang {
  const pref = getLangPref();
  lang = pref === 'auto' ? detectLang() : pref;
  t = DICTS[lang];
  try { document.documentElement.lang = lang; } catch { /* geen document */ }
  return lang;
}

export function setLangPref(pref: LangPref): void {
  try { if (pref === 'auto') localStorage.removeItem(KEY); else localStorage.setItem(KEY, pref); } catch { /* geen opslag */ }
  applyLang();
}

/** Kies de tekst voor de huidige taal uit een object per taal; valt terug op Engels en daarna Nederlands. */
export function pick<T>(v: Partial<Record<Lang, T>> & { nl: T }): T {
  return v[lang] ?? v.en ?? v.nl;
}

/** Weergavenaam van een soort attractie (interne sleutel is Nederlands). */
export const kindName = (kind: string): string => t.kinds[kind] ?? kind;

applyLang();
